function cleanText(text) {
  return String(text || '')
    .replace(/[\t\\]ext\{([^}]+)\}/g, '$1')
    .replace(/\\dots/g, '...')
    .replace(/ตามแนวข้อสอบต้นฉบับชุดที่ 3/g, 'ตามระเบียบงานสารบรรณ')
    .replace(/ตามตัวอย่างชุดที่ 3/g, 'ตามระเบียบงานสารบรรณ')
    .replace(/ตามตัวอย่างข้อสอบชุดที่ 3/g, 'ตามระเบียบงานสารบรรณ')
    .replace(/ตามกรอบของต้นฉบับชุดที่ 3/g, 'ตามระเบียบงานสารบรรณ')
    .replace(/ตามประเด็นที่ต้นฉบับชุดที่ 3 ใช้เป็นตัวเลือก/g, 'ตามระเบียบงานสารบรรณ')
    .replace(/ตามแนวข้อสอบชุดที่ 3/g, 'ตามระเบียบงานสารบรรณ')
    .replace(/ตามแนวคำถามต้นฉบับชุดที่ 3/g, 'ตามหลักกฎหมาย')
    .replace(/ตามแนวข้อสอบต้นฉบับ/g, 'ตามระเบียบงานสารบรรณ')
    .replace(/ตามแบบที่ข้อสอบต้นฉบับชุดที่ 3 ใช้/g, 'ตามระเบียบงานสารบรรณ')
    .replace(/ตามตัวอย่างระบบสารบรรณอิเล็กทรอนิกส์ของชุดที่ 3/g, 'ตามมาตรฐานระบบสารบรรณอิเล็กทรอนิกส์ภาครัฐ')
    .replace(/ตามลักษณะตัวอย่างชุดที่ 3/g, 'ตามมาตรฐานระบบไปรษณีย์อิเล็กทรอนิกส์ภาครัฐ')
    .replace(/ตามรูปแบบตัวอย่างชุดที่ 3/g, 'ตามมาตรฐานสารบรรณอิเล็กทรอนิกส์ภาครัฐ')
    .replace(/ตามนิยามที่ข้อสอบต้นฉบับใช้/g, 'ตามระเบียบงานสารบรรณ')
    .replace(/ตามคาแรกเตอร์ของต้นฉบับ/g, 'ตามระเบียบงานสารบรรณ')
    .replace(/ตามคาแรกเตอร์ต้นฉบับ/g, 'ตามระเบียบงานสารบรรณ')
    .replace(/ตามลักษณะข้อสอบต้นฉบับ/g, 'ตามระเบียบงานสารบรรณ')
    .replace(/ตามข้อสอบต้นฉบับ/g, 'ตามระเบียบงานสารบรรณ')
    .replace(/ตามแนวคำถามต้นฉบับ/g, 'ตามระเบียบงานสารบรรณ')
    .replace(/ตามตัวอย่างที่โจทย์นำมาเทียบ/g, 'ตามหลักเกณฑ์')
    .replace(/ตรงกับเฉลยต้นฉบับชุดที่ 3 ข้อ \d+ และข้อ \d+/g, 'ตามหลักกฎหมาย')
    .replace(/ตรงกับเฉลยต้นฉบับชุดที่ 3 ข้อ \d+/g, 'ตามหลักกฎหมาย')
    .replace(/ต้นฉบับชุดที่ 3/g, 'ระเบียบงานสารบรรณ')
    .replace(/ต้นฉบับ/g, 'ระเบียบงานสารบรรณ')
    .replace(/ชุดที่ 3/g, 'ระเบียบงานสารบรรณ');
}

function normalizeDifficulty(rawDiff, defaultVal = 'medium') {
  if (!rawDiff) return defaultVal;
  const d = String(rawDiff).trim().toLowerCase();
  if (d === 'ง่าย' || d === 'easy') return 'easy';
  if (d === 'ปานกลาง' || d === 'medium') return 'medium';
  if (d === 'ยาก' || d === 'hard') return 'hard';
  return defaultVal;
}

