#!/usr/bin/env node

import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const slugs = ['foundations', 'algebra', 'ratios-percent', 'geometry', 'stats-prob', 'aptitude-logic'];
const categories = slugs.map((slug) => {
  const file = path.join(root, 'content/exams', `police-math-set-02-${slug}.json`);
  return JSON.parse(fs.readFileSync(file, 'utf8'));
});

const bundle = {
  bundleId: 'police-math-set-02',
  title: 'Set 2: ข้อสอบแยกหมวด ความรู้ความสามารถทั่วไป',
  totalQuestions: categories.reduce((total, category) => total + category.questions.length, 0),
  categories
};

const output = path.join(root, 'exports', 'police-math-set-02-all.js');
fs.mkdirSync(path.dirname(output), { recursive: true });
fs.writeFileSync(
  output,
  `// Generated from content/exams/police-math-set-02-*.json. Do not edit this file directly.\nexport default ${JSON.stringify(bundle, null, 2)};\n`
);
console.log(`Wrote ${output} with ${bundle.totalQuestions} questions.`);
